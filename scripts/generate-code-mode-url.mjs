#!/usr/bin/env node
// Build the pinned URL implementation as source evaluated only inside QuickJS.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { format } from "oxfmt";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(join(root, "package.json"));
const outputPath = join(root, "src/agents/code-mode-url-source.generated.ts");
const check = process.argv.slice(2).includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/generate-code-mode-url.mjs [--check]");
}
const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const expectedVersion = manifest.dependencies["whatwg-url"];
if (typeof expectedVersion !== "string" || !/^\d+\.\d+\.\d+$/u.test(expectedVersion)) {
  throw new Error("whatwg-url must be an exact direct dependency before URL generation.");
}
const entry = require.resolve("whatwg-url");
const dependency = JSON.parse(await readFile(join(dirname(entry), "package.json"), "utf8"));
if (dependency.name !== "whatwg-url" || dependency.version !== expectedVersion) {
  throw new Error(
    "Installed whatwg-url differs from the direct pin; reconcile dependencies first.",
  );
}
// Bundle the exact entry whose package identity was checked, not a second
// independent lookup through the bundler's resolution rules.
const source =
  "import { URL, URLSearchParams } from " +
  JSON.stringify(entry) +
  "; " +
  "Object.defineProperties(globalThis, { URL: {value: URL, writable: true, configurable: true}, " +
  "URLSearchParams: {value: URLSearchParams, writable: true, configurable: true} });";
const bundle = await build({
  absWorkingDir: root,
  stdin: { contents: source, resolveDir: root, sourcefile: "code-mode-url-entry.js" },
  bundle: true,
  write: false,
  // This is a bare JS engine, not a browser or Node environment. In particular,
  // the bytes dependency's browser target requires native Latin-1 decoding.
  platform: "neutral",
  mainFields: ["main"],
  format: "iife",
  minify: true,
  legalComments: "inline",
  metafile: true,
});
if (
  bundle.outputFiles.length !== 1 ||
  Object.values(bundle.metafile.outputs).some((output) => output.imports.length > 0)
) {
  throw new Error("The guest URL asset must be a single bundle with no external imports.");
}

// Include each incorporated package's actual license, rather than assuming
// source-file legal comments cover package-level notices. Paths stay out of it.
const packages = new Map();
for (const input of Object.keys(bundle.metafile.inputs)) {
  if (input === "code-mode-url-entry.js") {
    continue;
  }
  let directory = dirname(resolve(root, input));
  while (directory !== dirname(directory)) {
    let metadata;
    try {
      metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw error;
      }
      directory = dirname(directory);
      continue;
    }
    if (typeof metadata.name !== "string" || typeof metadata.version !== "string") {
      throw new Error("Bundled dependency metadata is incomplete.");
    }
    const key = metadata.name + "@" + metadata.version;
    if (!packages.has(key)) {
      let license;
      for (const filename of [
        "LICENSE",
        "LICENSE.txt",
        "LICENSE.md",
        "LICENSE-MIT.txt",
        "license",
        "license.md",
      ]) {
        try {
          license = await readFile(join(directory, filename), "utf8");
          break;
        } catch (error) {
          if (error.code !== "ENOENT") {
            throw error;
          }
        }
      }
      if (!license) {
        throw new Error("Missing incorporated license for " + key);
      }
      packages.set(key, license.replaceAll("\r\n", "\n").trim());
    }
    break;
  }
}
const notices = [...packages]
  .toSorted(([a], [b]) => a.localeCompare(b, "en"))
  .map(([name, license]) => name + "\n" + license)
  .join("\n\n");
const guestSource =
  "/*! Bundled Code Mode URL licenses\n" +
  notices.replaceAll("*/", "* /") +
  "\n*/\n" +
  bundle.outputFiles[0].text;
const generated =
  "// Generated by pnpm code-mode:url:gen. Do not edit.\n" +
  "// Pinned whatwg-url " +
  expectedVersion +
  "; pure guest source, no host imports.\n" +
  "export const CODE_MODE_URL_SOURCE =\n  " +
  JSON.stringify(guestSource) +
  ";\n";
const formatted = await format(outputPath, generated);
if (formatted.errors.length > 0) {
  throw new Error("Generated URL source could not be formatted.");
}
if (check) {
  let current;
  try {
    current = await readFile(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") {
      throw error;
    }
  }
  if (current !== formatted.code) {
    throw new Error("Code Mode URL asset is stale or missing; run pnpm code-mode:url:gen.");
  }
} else {
  await writeFile(outputPath, formatted.code);
}
console.log(
  "Code Mode URL asset " +
    (check ? "verified" : "generated") +
    ": " +
    Buffer.byteLength(guestSource) +
    " bytes; " +
    packages.size +
    " licensed packages; no external imports.",
);
