// Message-tool idempotency key and delivery fingerprint helpers.
// Extracted from message-tool-execution to keep that module within the lint line budget.
import { normalizeOptionalString } from "@openclaw/normalization-core/string-coerce";
import type { ChannelMessageActionName } from "../../channels/plugins/types.public.js";
import { sha256Base64UrlPrefix } from "../../infra/crypto-digest.js";
import type { GatewayCallOptions } from "./gateway.js";

function normalizeMessageToolIdempotencyKeyPart(value: unknown): string | undefined {
  return normalizeOptionalString(value)?.replace(/[^A-Za-z0-9._:-]+/gu, "_");
}

const MESSAGE_TOOL_IDEMPOTENCY_ENVELOPE_PARAM_KEYS = new Set<string>([
  "gatewayToken",
  "gatewayUrl",
  "idempotencyKey",
  "timeoutMs",
] satisfies Array<keyof GatewayCallOptions | "idempotencyKey">);

function stripMessageToolIdempotencyEnvelope(
  params: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const key of Object.keys(params).toSorted()) {
    if (!MESSAGE_TOOL_IDEMPOTENCY_ENVELOPE_PARAM_KEYS.has(key)) {
      out[key] = params[key];
    }
  }
  return out;
}

function canonicalizeMessageToolIdempotencyValue(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((entry) => canonicalizeMessageToolIdempotencyValue(entry));
  }
  if (!value || typeof value !== "object") {
    return value;
  }
  // SAFETY: narrowed by the `typeof value !== "object"` guard above; treat the remaining object as a string-keyed record for canonical ordering.
  const record = value as Record<string, unknown>;
  const out: Record<string, unknown> = {};
  for (const key of Object.keys(record).toSorted()) {
    out[key] = canonicalizeMessageToolIdempotencyValue(record[key]);
  }
  return out;
}

type MessageToolIdempotencyInput = {
  action: ChannelMessageActionName;
  params: Record<string, unknown>;
  explicitIdempotencyKey: unknown;
  runId: string | undefined;
  toolCallId: string;
  failedAutogeneratedKeys: Map<string, string>;
  nextOperationId: () => string;
};

export function deriveMessageToolIdempotency(input: MessageToolIdempotencyInput): {
  actionIdempotencyKey: string | undefined;
  autogeneratedDeliveryFingerprint: string | undefined;
} {
  const actionIdempotencyKey = normalizeOptionalString(input.explicitIdempotencyKey);
  if (actionIdempotencyKey || !input.runId) {
    return { actionIdempotencyKey, autogeneratedDeliveryFingerprint: undefined };
  }
  const autogeneratedDeliveryFingerprint = sha256Base64UrlPrefix(
    JSON.stringify(
      canonicalizeMessageToolIdempotencyValue({
        action: input.action,
        params: stripMessageToolIdempotencyEnvelope(input.params),
      }),
    ),
    24,
  );
  const resolvedKey =
    input.failedAutogeneratedKeys.get(autogeneratedDeliveryFingerprint) ??
    `${normalizeMessageToolIdempotencyKeyPart(input.runId) ?? input.runId}:message-tool:${autogeneratedDeliveryFingerprint}:${
      normalizeMessageToolIdempotencyKeyPart(input.toolCallId) ?? input.nextOperationId()
    }`;
  return { actionIdempotencyKey: resolvedKey, autogeneratedDeliveryFingerprint };
}
