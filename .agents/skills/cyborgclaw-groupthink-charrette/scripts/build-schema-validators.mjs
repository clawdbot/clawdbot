#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { decodeUtf8Strict, parseJsonStrict, sha256 } from "./json-utils.mjs";

const skillRoot = fileURLToPath(new URL("..", import.meta.url));
const outputPath = join(skillRoot, "scripts", "generated-schema-validators.mjs");
const draftUri = "https://json-schema.org/draft/2020-12/schema";
// This matches the engine's exact ISO round trip for every four-digit Gregorian date,
// including the century exception for leap years. A shape-only date regex is insufficient.
const canonicalUtcTimestampPattern =
  /^(?:(?:\d{2}(?:0[48]|[2468][048]|[13579][26])|(?:00|0[48]|[2468][048]|[13579][26])00)-02-29|\d{4}-(?:(?:0[13578]|1[02])-(?:0[1-9]|[12]\d|3[01])|(?:0[469]|11)-(?:0[1-9]|[12]\d|30)|02-(?:0[1-9]|1\d|2[0-8])))T(?:[01]\d|2[0-3]):[0-5]\d:[0-5]\d\.\d{3}Z$/;
const schemaDefinitions = [
  {
    key: "session",
    validatorName: "validateSession",
    path: "references/SESSION_SCHEMA.json",
  },
  {
    key: "findings",
    validatorName: "validateFindings",
    path: "references/FINDINGS_SCHEMA.json",
  },
  {
    key: "decision_record",
    validatorName: "validateDecisionRecord",
    path: "references/DECISION_RECORD_SCHEMA.json",
  },
];

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

const require = createRequire(import.meta.url);
const ajvVersion = require("ajv/package.json").version;
assert(
  /^8\./.test(ajvVersion),
  `Schema validators require Ajv 8 at build time; received ${ajvVersion}`,
);

const schemas = [];
for (const definition of schemaDefinitions) {
  const absolutePath = join(skillRoot, ...definition.path.split("/"));
  const bytes = await readFile(absolutePath);
  const schema = parseJsonStrict(decodeUtf8Strict(bytes, absolutePath), absolutePath);
  assert(schema.$schema === draftUri, `${definition.path} is not Draft 2020-12`);
  assert(schema.type === "object", `${definition.path} must describe an object`);
  schemas.push({
    ...definition,
    id: schema.$id,
    sha256: sha256(bytes),
    schema,
  });
}

const ajv = new Ajv2020({
  allErrors: true,
  code: {
    esm: true,
    lines: true,
    optimize: 2,
    source: true,
  },
  formats: {
    "date-time": canonicalUtcTimestampPattern,
  },
  ownProperties: true,
  strict: true,
  // Shared action $defs carry property constraints while each call site supplies the type.
  strictTypes: false,
});

for (const item of schemas) {
  ajv.addSchema(item.schema, item.validatorName);
}

const exportsByName = Object.fromEntries(
  schemas.map((item) => [item.validatorName, item.validatorName]),
);
let generated = standaloneCode(ajv, exportsByName).replace(/^"use strict";\n/, "");

for (const item of schemas) {
  const exportedDeclaration = `export const ${item.validatorName} =`;
  assert(generated.includes(exportedDeclaration), `Ajv output omitted ${item.validatorName}`);
  generated = generated.replace(exportedDeclaration, `const ${item.validatorName} =`);
}

const runtimeReplacements = [
  [
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    "const $1 = standaloneUnicodeLength;",
  ],
  [
    /const (func\d+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/g,
    "const $1 = standaloneDeepEqual;",
  ],
];
for (const [pattern, replacement] of runtimeReplacements) {
  generated = generated.replace(pattern, replacement);
}
assert(!generated.includes("require("), "Ajv output retains an unbundled runtime dependency");

const metadata = {
  schema_version: "cyborgclaw.groupthink-charrette.schema-validator.v1",
  draft: draftUri,
  generator: {
    package: "ajv",
    version: ajvVersion,
    mode: "standalone-esm",
  },
  schemas: Object.fromEntries(
    schemas.map((item) => [
      item.key,
      {
        id: item.id,
        path: item.path,
        sha256: item.sha256,
      },
    ]),
  ),
};

const header = `// Generated by scripts/build-schema-validators.mjs. Do not edit by hand.
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const generatedSchemaValidatorMetadata = standaloneDeepFreeze(${JSON.stringify(metadata, null, 2)});

function standaloneDeepFreeze(value) {
  for (const child of Object.values(value)) {
    if (child !== null && typeof child === "object") {
      standaloneDeepFreeze(child);
    }
  }
  return Object.freeze(value);
}

function standaloneUnicodeLength(value) {
  let length = 0;
  for (let index = 0; index < value.length; index += 1) {
    length += 1;
    const high = value.charCodeAt(index);
    if (
      high >= 0xd800 &&
      high <= 0xdbff &&
      index + 1 < value.length &&
      (value.charCodeAt(index + 1) & 0xfc00) === 0xdc00
    ) {
      index += 1;
    }
  }
  return length;
}

function standaloneDeepEqual(left, right) {
  if (left === right) {
    return true;
  }
  if (
    left === null ||
    right === null ||
    typeof left !== "object" ||
    typeof right !== "object"
  ) {
    return Number.isNaN(left) && Number.isNaN(right);
  }
  if (Array.isArray(left) || Array.isArray(right)) {
    return (
      Array.isArray(left) &&
      Array.isArray(right) &&
      left.length === right.length &&
      left.every((item, index) => standaloneDeepEqual(item, right[index]))
    );
  }
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  return (
    leftKeys.length === rightKeys.length &&
    leftKeys.every(
      (key) =>
        Object.hasOwn(right, key) && standaloneDeepEqual(left[key], right[key]),
    )
  );
}

`;

const footer = `
const generatedValidators = Object.freeze({
  session: ${schemaDefinitions[0].validatorName},
  findings: ${schemaDefinitions[1].validatorName},
  decision_record: ${schemaDefinitions[2].validatorName},
});

const defaultSkillRoot = fileURLToPath(new URL("..", import.meta.url));

export async function assertGeneratedSchemaValidatorsCurrent(root = defaultSkillRoot) {
  const resolvedRoot = resolve(root);
  for (const contract of Object.values(generatedSchemaValidatorMetadata.schemas)) {
    const path = join(resolvedRoot, ...contract.path.split("/"));
    const bytes = await readFile(path);
    try {
      new TextDecoder("utf-8", { fatal: true }).decode(bytes);
    } catch {
      throw new Error(\`Schema validator input is not strict UTF-8: \${contract.path}\`);
    }
    const actual = createHash("sha256").update(bytes).digest("hex");
    if (actual !== contract.sha256) {
      throw new Error(
        \`Generated schema validator is stale for \${contract.path}: expected \${contract.sha256}, received \${actual}\`,
      );
    }
  }
  return generatedSchemaValidatorMetadata;
}

export async function loadGeneratedSchemaValidators(root = defaultSkillRoot) {
  await assertGeneratedSchemaValidatorsCurrent(root);
  return generatedValidators;
}
`;

await writeFile(outputPath, `${header}${generated}${footer}`, "utf8");
process.stdout.write(
  `${JSON.stringify(
    {
      generated: outputPath,
      generator: metadata.generator,
      schemas: metadata.schemas,
    },
    null,
    2,
  )}\n`,
);
